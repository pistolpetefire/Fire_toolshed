"""Independent Python hand calcs for the atrium Verification pages.
Writes shared/atrium-handcalc.mjs. Run from the repo root: python3 validation/atrium_handcalc.py
Each value is computed here from the equations, not by calling the app's JavaScript."""
import json, math, os
root=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
R={}
Qc=3500.0; z=100.0                                   # NFPA 92 Annex K.1.2 (IP)
zl=0.533*Qc**0.4; R["nfpa92-k12-zl"]=zl
m=0.022*Qc**(1/3)*z**(5/3)+0.0042*Qc; R["nfpa92-k12-m"]=m
V=m/0.075; R["nfpa92-k12-v"]=V
R["nfpa92-k12-dt"]=Qc/(0.075*0.24*V)
R["balcony-substitution"]=0.36*(1000*5**2)**(1/3)*(6+0.25*4)
# Zone check: steady 1400 kW, A = 40 x 30 m, H = 20 m, rho 1.2, entrainment 0.071 Qc^(1/3) z^(5/3) only.
# Independent RK4 integration of A dz/dt = -m(z)/rho (layer of ambient-density smoke), t = 0..120 s.
Q=1400.0; A=1200.0; H=20.0; rho=1.2
f=lambda zz: -(0.071*Q**(1/3)*max(zz,0)**(5/3))/(rho*A)
zz=H; dt=0.01
for _ in range(int(round(120/dt))):
    k1=f(zz);k2=f(zz+dt/2*k1);k3=f(zz+dt/2*k2);k4=f(zz+dt*k3); zz+=dt/6*(k1+2*k2+2*k3+k4)
R["zone-closed-form"]=zz
R["_zone_closed_form_check"]=H*(1+(2/3)*(0.071*Q**(1/3)/(rho*A))*120*H**(2/3))**-1.5
js=("// Generated by validation/atrium_handcalc.py (independent Python hand calcs). Do not edit by hand.\n"
    f"export const PYTHON_REF = {json.dumps(R,indent=2)}\n")
open(os.path.join(root,"shared","atrium-handcalc.mjs"),"w").write(js); print(json.dumps(R,indent=1))
