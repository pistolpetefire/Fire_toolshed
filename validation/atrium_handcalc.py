"""Independent Python hand calcs for the atrium Verification pages.
Writes shared/atrium-handcalc.mjs. Run from the repo root: python3 validation/atrium_handcalc.py
Each value is computed here from the equations, not by calling the app's JavaScript."""
import json, math, os
root=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
R={}
Qc=3500.0; z=100.0                                   # NFPA 92 Annex K.1.2 (IP)
zl=0.533*Qc**0.4; R["nfpa92-k12-zl"]=zl
m=0.022*Qc**(1/3)*z**(5/3)+0.0042*Qc; R["nfpa92-k12-m"]=m
V=m/0.075; R["nfpa92-k12-v"]=V
R["nfpa92-k12-dt"]=Qc/(0.075*0.24*V)
R["balcony-substitution"]=0.36*(1000*5**2)**(1/3)*(6+0.25*4)
# Zone check: steady 1400 kW, A = 40 x 30 m, H = 20 m, ambient 20 C, entrainment 0.071 Qc^(1/3) z^(5/3) only, no exhaust.
# Independent RK4 integration of the same two-zone balance the app states: layer mass dm/dt = m_p(z),
# layer heat dE/dt = Qc, layer temperature T = T0 + E/(m cp), layer volume V = m T / 353, z = H - V/A, t = 0..120 s.
Q=1400.0; A=1200.0; H=20.0; T0=293.15; cp=1.0
def zof(m,E):
    if m<=1e-12: return H
    T=T0+E/(m*cp); return H-(m*T/353.0)/A
def dm(m,E): return 0.071*Q**(1/3)*max(zof(m,E),0.2)**(5/3)
m=0.0; E=0.0; dt=0.01
for _ in range(int(round(120/dt))):
    k1=dm(m,E); k2=dm(m+dt/2*k1,E+dt/2*Q); k3=dm(m+dt/2*k2,E+dt/2*Q); k4=dm(m+dt*k3,E+dt*Q)
    m+=dt/6*(k1+2*k2+2*k3+k4); E+=dt*Q
R["zone-closed-form"]=zof(m,E)
# For information only: the published ambient-density closed form (no layer expansion, rho 1.2). It reads about 2% higher
# because hot smoke takes more volume than ambient-density smoke; the Verification row keeps its 5% tolerance against it.
rho=1.2
R["_zone_closed_form_check"]=H*(1+(2/3)*(0.071*Q**(1/3)/(rho*A))*120*H**(2/3))**-1.5
js=("// Generated by validation/atrium_handcalc.py (independent Python hand calcs). Do not edit by hand.\n"
    f"export const PYTHON_REF = {json.dumps(R,indent=2)}\n")
open(os.path.join(root,"shared","atrium-handcalc.mjs"),"w").write(js); print(json.dumps(R,indent=1))
