"""Shared writer for the batch 2 Verification tab. Each app script computes its reference values
independently in Python (it never calls the app's JavaScript) and writes <app>/assets/verify-cases.js."""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
def write(app_dir, cfg):
    path = os.path.join(ROOT, app_dir, 'assets', 'verify-cases.js')
    os.makedirs(os.path.dirname(path), exist_ok=True)
    body = ("// Generated by validation/verify/%s (independent Python hand calcs). Do not edit by hand.\n"
            "window.FT_VERIFY_CASES = %s\n") % (cfg['script'], json.dumps(cfg, indent=1, ensure_ascii=False))
    open(path, 'w').write(body)
    print('wrote', path, sum(len(c['reads']) for c in cfg['cases']), 'checks')
def r(x, n=4):
    return float(round(x, n))
