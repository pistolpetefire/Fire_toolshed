"""Independent Python hand calcs for the Transparent RSET Tool Verification panel.
Writes src/lib/verificationReference.ts. Run from rset-tool/: python3 validation/rset_handcalc.py"""
import json, math, os
here=os.path.dirname(os.path.abspath(__file__)); root=os.path.dirname(here)
fixture=open(os.path.join(here,"fixtures","aset-screener-project.json")).read()
aset=json.loads(fixture)["results"]["asetGoverning_s"]
def fmt_time(s):
    sign="-" if s<0 else ""; a=abs(s)
    if a<60: return f"{sign}{a:.0f} s"
    m=int(a//60); r=int(math.floor(a%60+0.5))
    return f"{sign}{m} min" if r==0 else f"{sign}{m} min {r} s"
def status(a,r,k): return "fail" if a<r else ("marginal" if a<k*r else "pass")
sets={"A":[45,30,120,180],"B":[0,0,0,0],"C":[12.5,7.25,90,333.3]}
cases=[]
for k,v in sets.items(): cases.append({"id":f"V1{k}","desc":f"RSET = D + N + P + M for {v} s","kind":"sum","input":v,"expected":sum(v),"unit":"s"})
cases.append({"id":"V2","desc":"Margin = ASET − RSET (ASET 594.3 s, RSET 375 s)","kind":"margin","input":[594.3,375],"expected":594.3-375,"unit":"s"})
cases.append({"id":"V3","desc":"ASET / RSET ratio (594.3 / 375)","kind":"ratio","input":[594.3,375,1.5],"expected":594.3/375,"unit":"–"})
for a,r,q in [(594.3,375,1.5),(594.3,375,2.0),(300,375,1.0)]:
    cases.append({"id":f"V4{'abc'[len([c for c in cases if c['kind']=='status'])]}","desc":f"Status for ASET {a} s, RSET {r} s, required ratio {q}","kind":"status","input":[a,r,q],"expected":status(a,r,q),"unit":""})
for i,s in enumerate([443.05,59.4,120,-75]):
    cases.append({"id":f"V5{'abcd'[i]}","desc":f"Time format of {s} s","kind":"format","input":s,"expected":fmt_time(s),"unit":""})
cases.append({"id":"V6a","desc":"Negative duration clamps to 0 s","kind":"clamp","input":-5,"expected":0,"unit":"s"})
cases.append({"id":"V7","desc":"ASET Screener file: governing ASET read","kind":"asetImport","input":None,"expected":aset,"unit":"s"})
ts=("// Generated by validation/rset_handcalc.py (independent Python hand calcs). Do not edit by hand.\n"
    "export interface RefCase { id: string; desc: string; kind: 'sum' | 'margin' | 'ratio' | 'status' | 'format' | 'clamp' | 'asetImport'; input: unknown; expected: number | string; unit: string }\n"
    f"export const REF_CASES: RefCase[] = {json.dumps(cases,ensure_ascii=False,indent=1)}\n"
    f"export const REF_ASET_FIXTURE: string = {json.dumps(fixture)}\n")
open(os.path.join(root,"src","lib","verificationReference.ts"),"w").write(ts)
print(json.dumps(cases,ensure_ascii=False,indent=0)[:1500])
